_LOCALE: contextvars.ContextVar[str] = contextvars.ContextVar("trans_mcp_locale", default="")


def normalize(locale) -> str:
    """把 zh-CN、EN_US、ja_JP 这类写法归一到支持的九种，认不出返回空串"""
    if not locale or not isinstance(locale, str):
        return ""
    tag = locale.strip().replace("_", "-")
    if not tag:
        return ""
    lowered = tag.lower()
    if lowered in _ALIASES:
        return _ALIASES[lowered]
    for supported in SUPPORTED_LOCALES:
        if lowered == supported.lower():
            return supported
    # en-US → en，de-AT → de
    primary = lowered.split("-", 1)[0]
    for supported in SUPPORTED_LOCALES:
        if primary == supported.lower():
            return supported
    return ""


def env_locale() -> str:
    return normalize(os.environ.get("MCP_LOCALE"))


def resolve(locale=None) -> str:
    """参数 > 环境变量 > zh。传了不认识的值不报错，按兜底走。"""
    return normalize(locale) or env_locale() or DEFAULT_LOCALE


def use_locale(locale=None):
    """进入一次工具调用时设定语言，返回的 token 交给 reset_locale"""
    return _LOCALE.set(resolve(locale))


def reset_locale(token) -> None:
    _LOCALE.reset(token)


def current() -> str:
    return _LOCALE.get() or resolve(None)


def t(key: str, **kwargs) -> str:
    """取一条文案。某语言缺这条就回退中文，中文也没有就把 key 原样返回——
    宁可露出 key 也不要静默地少一句话。"""
    table = MESSAGES.get(current()) or {}
    text = table.get(key) or MESSAGES[DEFAULT_LOCALE].get(key)
    if text is None:
        return key
    if not kwargs:
        return text
    try:
        return text.format(**kwargs)
    except (KeyError, IndexError):
        return text
